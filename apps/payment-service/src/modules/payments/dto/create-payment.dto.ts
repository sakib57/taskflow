import { ApiProperty } from '@nestjs/swagger';
import { IsString, IsNumber, IsPositive, IsIn, Length } from 'class-validator';

export class CreatePaymentDto {
  @ApiProperty({ example: 99.99 })
  @IsNumber()
  @IsPositive()
  amount: number;

  @ApiProperty({ example: 'USD' })
  @IsString()
  @Length(3, 3)
  currency: string;

  @ApiProperty({ example: 'stripe', enum: ['stripe', 'bkash'] })
  @IsString()
  @IsIn(['stripe', 'bkash'])
  paymentMethod: string;

  @ApiProperty({
    example: 'idempotency-key-unique-1234',
    description: 'Unique key generated by client to prevent double charges',
  })
  @IsString()
  @Length(10, 255)
  idempotencyKey: string;
}
